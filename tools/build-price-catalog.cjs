'use strict';
const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..');const data=JSON.parse(fs.readFileSync(path.join(root,'dist/data.json'),'utf8'));
const records=Object.fromEntries(data.records.filter(r=>r.is_watch&&r.price_value==null&&r.reference_number?.length>=3).map(r=>[r.id,{brand:r.brand,reference:r.reference_number,model:r.specific_model}]));
fs.mkdirSync(path.join(root,'backend'),{recursive:true});
fs.writeFileSync(path.join(root,'backend/catalog.mjs'),'// Generated by tools/build-price-catalog.cjs; public, eligible watch identities only.\nexport default '+JSON.stringify(records)+';\n');
console.log(`Prepared ${Object.keys(records).length} eligible price lookup identities.`);
